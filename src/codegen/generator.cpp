    void CppGenerator::generate(const topologos::ast::Node* root) {
        if (!root) return;

        // ProgramNode로 시작
        if (auto program = dynamic_cast<const topologos::ast::ProgramNode*>(root)) {
            visit_program(program);
        }
    }

    void CppGenerator::visit_program(const topologos::ast::ProgramNode* node) {
        mermaid_ss_ << "graph TD;\n";
        mermaid_ss_ << "    %% Generated by TopoLogos Compiler\n";
        
        // [Fix] children -> domains (구체적 타입 순회)
        for (const auto& domain : node->domains) {
            // unique_ptr/shared_ptr로 가정하고 get() 사용
            // 만약 스마트 포인터가 아니라면 &domain으로 변경 필요
            visit_domain(domain.get());
        }
    }

    void CppGenerator::visit_domain(const topologos::ast::DomainNode* node) {
        mermaid_ss_ << "    subgraph " << node->name << "\n";
        
        // [Fix] children -> axioms
        for (const auto& axiom : node->axioms) {
            visit_axiom(axiom.get());
        }
        
        mermaid_ss_ << "    end\n";
    }

    void CppGenerator::visit_axiom(const topologos::ast::AxiomNode* node) {
        mermaid_ss_ << "    " << node->name << "[Axiom: " << node->name << "]\n";
        
        // [Fix] children -> rules
        for (const auto& rule : node->rules) {
            visit_rule(rule.get());
            // 시각화: Axiom -> Rule 연결선
            mermaid_ss_ << "    " << node->name << " --> " << rule->name << "\n";
        }
    }

    void CppGenerator::visit_rule(const topologos::ast::RuleNode* node) {
        mermaid_ss_ << "    " << node->name << "(Rule: " << node->name << ")\n";
    }

